-- ====================================================================================
-- SISTEMA DE VÍNCULO DE NORMAS/LEIS AO EDITAL DO CURSO
-- Permite filtrar questões, flashcards e resumos por lei/norma específica
-- Zero-breaking: apenas ADDs, nenhuma coluna existente é alterada ou removida
-- Execute este script UMA VEZ no Supabase SQL Editor
-- ====================================================================================

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. Tabela de Normas/Leis (catálogo único de referências legislativas)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.law_references (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT NOT NULL,        -- ex: "Lei Federal nº 14.133/2021 – Licitações"
  short_name  TEXT,                 -- ex: "Lei 14.133/2021"
  topic_id    BIGINT REFERENCES public.topics(id) ON DELETE SET NULL,
  -- (Opcional) vincula a norma a um tópico pai para organização hierárquica
  description TEXT,
  is_active   BOOLEAN DEFAULT TRUE,
  created_at  TIMESTAMPTZ DEFAULT now()
);

COMMENT ON TABLE  public.law_references IS 'Catálogo unificado de normas, leis e atos normativos usados como referência de conteúdo.';
COMMENT ON COLUMN public.law_references.name       IS 'Nome completo: ex "Lei 14.133 de 01/04/2021 – Lei de Licitações e Contratos"';
COMMENT ON COLUMN public.law_references.short_name IS 'Versão curta exibida em tags: ex "Lei 14.133/2021"';
COMMENT ON COLUMN public.law_references.topic_id   IS 'Tópico ao qual esta norma pertence (opcional, para organização)';

CREATE INDEX IF NOT EXISTS idx_law_refs_topic ON public.law_references(topic_id);

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. Pivot: Edital ↔ Normas permitidas
--    Define quais normas fazem parte de um edital (curso)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.edital_law_references (
  edital_id       BIGINT NOT NULL REFERENCES public.edicts(id) ON DELETE CASCADE,
  law_reference_id BIGINT NOT NULL REFERENCES public.law_references(id) ON DELETE CASCADE,
  PRIMARY KEY (edital_id, law_reference_id)
);

COMMENT ON TABLE public.edital_law_references IS 'Pivot entre editais e normas: define quais leis um edital específito exige.';

CREATE INDEX IF NOT EXISTS idx_edital_law_edital ON public.edital_law_references(edital_id);
CREATE INDEX IF NOT EXISTS idx_edital_law_law    ON public.edital_law_references(law_reference_id);

-- ─────────────────────────────────────────────────────────────────────────────
-- 3. Adiciona coluna law_reference_id em questions, flashcards e summaries
--    Nullable: conteúdo sem vínculo a lei continua funcionando normalmente
-- ─────────────────────────────────────────────────────────────────────────────
ALTER TABLE public.questions
  ADD COLUMN IF NOT EXISTS law_reference_id BIGINT REFERENCES public.law_references(id) ON DELETE SET NULL;

ALTER TABLE public.flashcards
  ADD COLUMN IF NOT EXISTS law_reference_id BIGINT REFERENCES public.law_references(id) ON DELETE SET NULL;

ALTER TABLE public.summaries
  ADD COLUMN IF NOT EXISTS law_reference_id BIGINT REFERENCES public.law_references(id) ON DELETE SET NULL;

COMMENT ON COLUMN public.questions.law_reference_id   IS 'Norma/Lei específica à qual esta questão se refere (pode ser NULL para conteúdo geral)';
COMMENT ON COLUMN public.flashcards.law_reference_id  IS 'Norma/Lei específica à qual este flashcard se refere';
COMMENT ON COLUMN public.summaries.law_reference_id   IS 'Norma/Lei específica à qual este resumo se refere';

CREATE INDEX IF NOT EXISTS idx_questions_law   ON public.questions(law_reference_id);
CREATE INDEX IF NOT EXISTS idx_flashcards_law  ON public.flashcards(law_reference_id);
CREATE INDEX IF NOT EXISTS idx_summaries_law   ON public.summaries(law_reference_id);

-- ─────────────────────────────────────────────────────────────────────────────
-- 4. RLS: Regras de segurança
-- ─────────────────────────────────────────────────────────────────────────────
ALTER TABLE public.law_references        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.edital_law_references ENABLE ROW LEVEL SECURITY;

-- Normas: leitura pública (todos podem enxergar o catálogo), admin gerencia
DROP POLICY IF EXISTS "Leitura livre law_references" ON public.law_references;
CREATE POLICY "Leitura livre law_references" ON public.law_references
  FOR SELECT USING (true);

DROP POLICY IF EXISTS "Admin gerencia law_references" ON public.law_references;
CREATE POLICY "Admin gerencia law_references" ON public.law_references
  FOR ALL USING (public.is_admin_user());

-- Pivot edital↔leis: leitura pública, admin gerencia
DROP POLICY IF EXISTS "Leitura livre edital_law_references" ON public.edital_law_references;
CREATE POLICY "Leitura livre edital_law_references" ON public.edital_law_references
  FOR SELECT USING (true);

DROP POLICY IF EXISTS "Admin gerencia edital_law_references" ON public.edital_law_references;
CREATE POLICY "Admin gerencia edital_law_references" ON public.edital_law_references
  FOR ALL USING (public.is_admin_user());

-- ─────────────────────────────────────────────────────────────────────────────
-- 5. View auxiliar: mostra quais leis estão ativas para cada curso
--    (une pelo edital vinculado ao curso)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE OR REPLACE VIEW public.v_course_active_laws
WITH (security_invoker = true) AS
SELECT
  c.id                    AS course_id,
  c.name                  AS course_name,
  e.id                    AS edital_id,
  e.name                  AS edital_name,
  lr.id                   AS law_reference_id,
  lr.name                 AS law_name,
  lr.short_name           AS law_short_name,
  lr.topic_id             AS topic_id
FROM
  public.courses          c
  JOIN public.edicts      e  ON e.course_id = c.id
  JOIN public.edital_law_references elr ON elr.edital_id = e.id
  JOIN public.law_references        lr  ON lr.id = elr.law_reference_id
WHERE
  lr.is_active = true;

COMMENT ON VIEW public.v_course_active_laws IS
  'View auxiliar: lista todas as normas ativas de cada curso (via edital → leis vinculadas). Use para filtrar questões/flashcards/resumos.';

