-- ============================================================================
-- MÓDULO PATRULHAMENTO - CRIAÇÃO DA INFRAESTRUTURA DE BANCO DE DADOS
-- Gamificação estilo Trilha (Linear, Auto-Build, Nível Curso)
-- ============================================================================

-- 1. Campanhas (Grandes Capítulos/Temporadas)
CREATE TABLE IF NOT EXISTS public.patrulhamento_campanhas (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id     BIGINT NOT NULL, -- O módulo é atrelado ao curso
  titulo        TEXT NOT NULL,
  descricao     TEXT,
  ordem         INTEGER NOT NULL DEFAULT 0,
  created_at    TIMESTAMPTZ DEFAULT now()
);

-- 2. Setores (Zonas dentro de uma Campanha, equivalente a blocos de fases)
CREATE TABLE IF NOT EXISTS public.patrulhamento_setores (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campanha_id   BIGINT NOT NULL REFERENCES public.patrulhamento_campanhas(id) ON DELETE CASCADE,
  titulo        TEXT NOT NULL,
  icone         TEXT DEFAULT 'MapPin',
  ordem         INTEGER NOT NULL DEFAULT 0,
  created_at    TIMESTAMPTZ DEFAULT now()
);

-- 3. Fases (Os "nós" da trilha: Teoria, Questões, Flashcards, Checkpoint)
-- O payload_json armazena as chaves dinâmicas. Exemplo: {"tema_id": 5}
CREATE TABLE IF NOT EXISTS public.patrulhamento_fases (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  setor_id      BIGINT NOT NULL REFERENCES public.patrulhamento_setores(id) ON DELETE CASCADE,
  tipo_fase     TEXT NOT NULL CHECK (tipo_fase IN ('teoria', 'questoes', 'flashcards', 'checkpoint')),
  titulo        TEXT NOT NULL,
  descricao     TEXT,
  req_acertos   INTEGER DEFAULT 0,  -- Para questoes/checkpoint: Mínimo de acertos
  limite_itens  INTEGER DEFAULT 5,  -- Quantidade de questoes/flashcards a puxar
  payload_json  JSONB DEFAULT '{}', -- Metadados (ex: topic_id p/ buscar questões dinâmicas)
  ordem_global  INTEGER NOT NULL,   -- Ordem GERAL de 1 a N, facilita o "Next Node"
  xp_reward     INTEGER DEFAULT 50, -- Quantidade de XP concedido ao passar
  created_at    TIMESTAMPTZ DEFAULT now()
);

-- 4. Progresso Geral do Aluno (Save Game)
-- Relacionamento 1 p/ 1 por (user_id, course_id)
CREATE TABLE IF NOT EXISTS public.patrulhamento_progresso (
  user_id       UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  course_id     BIGINT NOT NULL,
  fase_atual_id BIGINT REFERENCES public.patrulhamento_fases(id) ON DELETE SET NULL, -- A fase onde ele está preso/livre
  xp_total      INTEGER DEFAULT 0,
  fases_vencidas JSONB DEFAULT '[]',   -- Registro simples para pintar o mapa de completado [faseID1, faseID2...]
  last_activity TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (user_id, course_id)     -- O aluno só pode ter 1 save game por curso
);

-- Índices de performance
CREATE INDEX IF NOT EXISTS idx_patrulha_camp_curso ON public.patrulhamento_campanhas(course_id);
CREATE INDEX IF NOT EXISTS idx_patrulha_setor_camp ON public.patrulhamento_setores(campanha_id);
CREATE INDEX IF NOT EXISTS idx_patrulha_fase_setor ON public.patrulhamento_fases(setor_id);
CREATE INDEX IF NOT EXISTS idx_patrulha_fase_ordem ON public.patrulhamento_fases(ordem_global);

-- ============================================================================
-- SEGURANÇA E RLS (Row Level Security)
-- ============================================================================
ALTER TABLE public.patrulhamento_campanhas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.patrulhamento_setores ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.patrulhamento_fases ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.patrulhamento_progresso ENABLE ROW LEVEL SECURITY;

-- Select (Leitura): Alunos podem ler todo o mapa, mas só inserem no seu próprio progresso
CREATE POLICY "Leitura livre campanhas" ON public.patrulhamento_campanhas FOR SELECT USING (true);
CREATE POLICY "Leitura livre setores" ON public.patrulhamento_setores FOR SELECT USING (true);
CREATE POLICY "Leitura livre fases" ON public.patrulhamento_fases FOR SELECT USING (true);
CREATE POLICY "Admin All campanhas" ON public.patrulhamento_campanhas FOR ALL USING (public.is_admin_user());
CREATE POLICY "Admin All setores" ON public.patrulhamento_setores FOR ALL USING (public.is_admin_user());
CREATE POLICY "Admin All fases" ON public.patrulhamento_fases FOR ALL USING (public.is_admin_user());

-- Progresso do Aluno
CREATE POLICY "Aluno gerencia proprio progresso" ON public.patrulhamento_progresso
  FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

-- Para evitar erros caso admin tente ver analytics de outros alunos
CREATE POLICY "Admin ve progresso geral" ON public.patrulhamento_progresso
  FOR SELECT USING (public.is_admin_user());
